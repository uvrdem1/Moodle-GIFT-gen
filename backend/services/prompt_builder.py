from typing import Optional


def build_generation_prompt(
    topic: str,
    questions_count: int,
    language: str,
    question_type: str,
    answers_count: int,
    source_text: Optional[str] = ''
) -> str:

    language_name = (
        'Русский'
        if language == 'ru'
        else 'English'
    )

    question_rules = ''

    if question_type == 'single':

        question_rules = f'''
Каждый вопрос должен содержать ТОЛЬКО ОДИН правильный ответ.
Используй ровно {answers_count} вариантов ответа.
Неправильные ответы должны быть реалистичными и правдоподобными.
'''

    elif question_type == 'boolean':

        question_rules = '''
Создавай только TRUE/FALSE вопросы.
Не добавляй дополнительные варианты ответа.
'''

    elif question_type == 'multiple':

        question_rules = f'''
Каждый вопрос должен содержать НЕСКОЛЬКО правильных ответов.
Используй ровно {answers_count} вариантов ответа.
Неправильные ответы должны быть реалистичными и тематически связанными.
'''

    prompt = f"""
Ты — профессиональный преподаватель и эксперт
по созданию образовательных тестов.

Твоя задача — создать качественные тестовые вопросы
для системы Moodle.

Создай {questions_count} тестовых вопросов
в формате Moodle GIFT.

====================================
ТЕМАТИКА:
{topic}
====================================

====================================
ЯЗЫК:
{language_name}
====================================

====================================
ИСТОЧНИК МАТЕРИАЛА:
{source_text}
====================================

====================================
ТРЕБОВАНИЯ К ВОПРОСАМ:
{question_rules}
====================================

====================================
ОБЩИЕ ПРАВИЛА:
====================================

- Верни ТОЛЬКО Moodle GIFT format
- Не используй markdown
- Не добавляй пояснения
- Не добавляй комментарии
- Не добавляй техническую информацию
- Не добавляй нумерацию вручную
- Не используй слова:
  single,
  multiple,
  boolean
- Не указывай количество правильных ответов
- Не добавляй подсказки
- Не добавляй заголовки
- Не используй HTML
- Не используй символы форматирования

====================================
КАЧЕСТВО ВОПРОСОВ:
====================================

- Вопросы должны быть уникальными
- Вопросы должны быть академическими
- Вопросы должны проверять понимание темы
- Избегай слишком простых вопросов
- Избегай повторяющихся формулировок
- Неправильные ответы должны быть правдоподобными
- Все варианты ответа должны быть похожи по стилю
- Вопросы должны быть грамматически корректными

====================================
ОГРАНИЧЕНИЯ:
====================================

- Используй ТОЛЬКО предоставленный материал
- Не придумывай факты
- Не используй информацию вне текста
- Все вопросы должны быть на языке:
{language_name}

====================================
СТРОГИЙ ФОРМАТ GIFT:
====================================

Пример:

::Вопрос 1::
Что такое Python?
{{
=Язык программирования
~База данных
~Браузер
~Операционная система
}}

====================================
ВАЖНО:
====================================

Ответ должен содержать ТОЛЬКО готовый Moodle GIFT.
Без любого дополнительного текста.
"""

    return prompt